-- 1. Crear tabla de eventos de seguridad
create table if not exists public.eventos_seguridad (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    confianza_ia double precision not null,
    estado_alerta text default 'pendiente' not null,
    imagen text,
    modelos_positivos integer default 0,
    modelos_totales integer default 3
);

-- 2. Habilitar Row Level Security (RLS)
alter table public.eventos_seguridad enable row level security;

-- 3. Crear política de acceso total para inserción y lectura con las API Keys
drop policy if exists "Acceso total para clientes autorizados" on public.eventos_seguridad;
create policy "Acceso total para clientes autorizados" on public.eventos_seguridad
    for all using (true) with check (true);

-- 4. Índice para agilizar las consultas por fecha e ID
create index if not exists idx_eventos_seguridad_created_at on public.eventos_seguridad (created_at desc);
